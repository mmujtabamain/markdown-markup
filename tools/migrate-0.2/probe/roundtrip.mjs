#!/usr/bin/env node
// The probe's test: for each migrated document, 0.3 IR → source (ir3-source.mjs) → `mkp fmt --check`
// → `mkp check` → IR again, and whether that IR is the one it started from (the document's view and
// its own declarations, compared as JSON).
//
//   node probe/roundtrip.mjs <corpus work dir> [--mkp03 mkp]

import { spawnSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const [work] = process.argv.slice(2);
const i = process.argv.indexOf('--mkp03');
const mkp = resolve(i > 0 ? process.argv[i + 1] : join(here, '../../../targets/rust/target/release/mkp'));
const run = (argv) => spawnSync(argv[0], argv.slice(1), { encoding: 'utf8', maxBuffer: 64 << 20 });
// what the document says, with the IR's numbering (sites, binding and handler ids) taken out:
// bindings and handlers are put in where they are used
const own = (ir) => {
  const binds = new Map(ir.bindings.map((b) => [b.id, b.value]));
  const hs = new Map(ir.handlers.map((h) => [h.id, h.body]));
  const norm = (v) => {
    if (Array.isArray(v)) return v.map(norm);
    if (!v || typeof v !== 'object') return v;
    if ('bind' in v && Object.keys(v).length === 1) return norm(binds.get(v.bind));
    const o = {};
    for (const [k, x] of Object.entries(v)) {
      if (k === 'site') continue;
      o[k] = k === 'events' && x && typeof x === 'object' && !Array.isArray(x) ? Object.fromEntries(Object.entries(x).map(([e, h]) => [e, norm(hs.get(h) ?? h)])) : norm(x);
    }
    return o;
  };
  const doc = ir.templates.find((t) => t.name === 'doc');
  return JSON.stringify(norm({ view: doc.view, templates: ir.templates.filter((t) => t.name.startsWith('doc/')), decls: ir.declarations.filter((d) => JSON.stringify(d).includes('"doc/')), front: ir.front_matter }));
};
const rows = [];
for (const d of readdirSync(work).sort()) {
  const dir = join(work, d);
  if (!existsSync(join(dir, 'doc.mkp.md'))) continue;
  const packs = existsSync(join(dir, 'packs')) ? readdirSync(join(dir, 'packs')).map((p) => join(dir, 'packs', p)) : [];
  const pk = packs.length ? ['--pack', packs.join(',')] : [];
  const b1 = run([mkp, 'build', join(dir, 'doc.mkp.md'), ...pk, '--out', join(dir, 'a.ir.json')]);
  if (b1.status !== 0) continue; // the migrated document doesn't compile: nothing to write back
  const src = run(['node', join(here, 'ir3-source.mjs'), join(dir, 'a.ir.json')]);
  const out = join(dir, 'from-ir.mkp.md');
  writeFileSync(out, src.stdout);
  const r = { doc: d, todo: (src.stdout.match(/^\/\/ TODO/gm) ?? []).length, lines: src.stdout.split('\n').length, astLines: readFileSync(join(dir, 'doc.mkp.md'), 'utf8').split('\n').length };
  r.fmt = run([mkp, 'fmt', '--check', out]).status === 0 ? 'canonical' : 'not canonical';
  const k = run([mkp, 'check', ...pk, out]);
  r.check = k.status === 0 ? 'clean' : (k.stdout + k.stderr).trim().split('\n')[0];
  if (k.status === 0) {
    run([mkp, 'build', out, ...pk, '--out', join(dir, 'b.ir.json')]);
    r.same = own(JSON.parse(readFileSync(join(dir, 'a.ir.json'), 'utf8')).ir) === own(JSON.parse(readFileSync(join(dir, 'b.ir.json'), 'utf8')).ir);
  }
  rows.push(r);
}
const n = (f) => rows.filter(f).length;
console.log(`${rows.length} documents written back from their 0.3 IR: ${n((r) => r.fmt === 'canonical')} pass mkp fmt --check, ${n((r) => r.check === 'clean')} check clean, ${n((r) => r.same)} give the same IR back, ${n((r) => r.todo)} have TODOs`);
for (const r of rows.filter((r) => r.check !== 'clean' || !r.same || r.fmt !== 'canonical')) console.log(`  ${r.doc}: ${r.fmt}, ${r.check}${r.same === false ? ', a different IR' : ''}`);
writeFileSync(join(work, 'roundtrip.json'), JSON.stringify(rows, null, 1));
const t = [
  '# The probe: 0.3 IR back to canonical source',
  '',
  `Generated by \`node tools/migrate-0.2/probe/roundtrip.mjs\`. Each migrated document that compiles was built to its 0.3 IR, written back to source by \`probe/ir3-source.mjs\` from the IR alone, and checked. "Same IR" compares the document's view, its own widgets and its own declarations, with sites and binding numbers taken out.`,
  '',
  '| Documents | Pass `mkp fmt --check` as written | Check clean | Same IR | With a TODO |',
  '|---|---|---|---|---|',
  `| ${rows.length} | ${n((r) => r.fmt === 'canonical')} | ${n((r) => r.check === 'clean')} | ${n((r) => r.same)} | ${n((r) => r.todo)} |`,
  '',
  '| Document | `mkp fmt --check` | `mkp check` | Same IR | Lines (from the IR / from the migration) |',
  '|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.doc} | ${r.fmt} | ${r.check === 'clean' ? 'clean' : r.check.replace(/\|/g, '\\|').replace(/^.*?error/, 'error').slice(0, 120)} | ${r.same === undefined ? '' : r.same ? 'yes' : 'no'} | ${r.lines} / ${r.astLines} |`),
];
writeFileSync(join(here, '..', 'RESULTS-ir3-source.md'), t.join('\n') + '\n');
