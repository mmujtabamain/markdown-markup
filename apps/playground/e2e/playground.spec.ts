// Every fixture case and every document renders in the web playground: the page loads it, the
// runtime renders it with no error boundary and no page errors, and its Markdown is written.
// Negative cases show the errors they expect.
import { expect, test } from '@playwright/test';

test('every case and document renders in the playground', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(String(e)));
  await page.goto('/');
  await page.waitForSelector('[data-mkp-ready]', { timeout: 120_000 });
  const ids = await page.$$eval('.pg-side a', (as) => as.map((a) => new URLSearchParams((a as HTMLAnchorElement).hash.slice(1)).get('e')!).filter(Boolean));
  expect(ids.length).toBeGreaterThan(20);
  const failures: string[] = [];
  let rendered = 0;
  for (const id of ids) {
    errors.length = 0;
    await page.goto(`/#${new URLSearchParams({ e: id })}`);
    await page.waitForFunction((want) => {
      const v = document.querySelector('[data-mkp-ready]');
      return !!v && document.querySelector('.pg-head strong')?.textContent !== null && location.hash.includes(encodeURIComponent(want).slice(0, 10));
    }, id);
    await page.waitForTimeout(150);
    const negative = await page.$('[data-pg-negative]');
    if (negative) {
      if ((await negative.getAttribute('data-pg-negative')) !== 'ok') failures.push(`${id}: the negative case did not fail as expected`);
      continue;
    }
    if (await page.$('[data-pg-failed]')) failures.push(`${id}: did not compile: ${await page.textContent('.pg-view')}`);
    const boundary = await page.$$eval('.pg-stage .mkp-error', (els) => els.map((e) => e.textContent));
    if (boundary.length) failures.push(`${id}: error boundary: ${boundary.join(' | ')}`);
    if (!(await page.$('.pg-stage .mkp-root > *'))) failures.push(`${id}: rendered nothing`);
    const md = await page.textContent('[data-pg-out="md"]');
    if (!md || !md.includes('generated by mkp')) failures.push(`${id}: no Markdown output`);
    if (errors.length) failures.push(`${id}: page errors: ${errors.join(' | ')}`);
    rendered++;
  }
  console.log(`rendered ${rendered} of ${ids.length} entries in the web playground`);
  expect(failures).toEqual([]);
});
