// @mkp/page: the standalone page's HTML, its Markdown, and the pictures it puts inside itself.
import { describe, expect, it } from 'vitest';
import { compile } from '@mkp/core';
import { htmlPage, markdownPage, markdownToHtml, pageTitle, pictureNames, withAssets } from '../src/index';

describe('htmlPage', () => {
  const page = htmlPage({ title: 'Tide & <time>', bundleJson: JSON.stringify({ text: '</script><script>alert(1)</script>' }), script: 'console.log("</script>")', fallbackHtml: '<p>Hello</p>' });

  it('keeps the bundle and the script inside their own script elements', () => {
    // the only </script> closings are the three script elements' own
    expect(page.match(/<\/script>/gi)).toHaveLength(3);
    expect(page).toContain('\\u003c/script>\\u003cscript>alert(1)\\u003c/script>');
    expect(page).toContain('console.log("<\\/script>")');
  });
  it('escapes the title, and carries the Markdown fallback, the theme switch and its own styles', () => {
    expect(page).toContain('<title>Tide &amp; &lt;time&gt;</title>');
    expect(page).toContain('<article class="mkp-md">\n<p>Hello</p>');
    expect(page).toContain("setAttribute('data-theme'");
    expect(page).toContain('.mkp-js .mkp-page > .mkp-md { display: none; }');
  });
  it('a Markdown page has no script but the theme switch', () => {
    const md = markdownPage({ title: 'T', html: '<p>x</p>' });
    expect(md.match(/<script>/g)).toHaveLength(1);
    expect(md).not.toContain("classList.add('mkp-js')");
    expect(md).not.toContain('mkp-bundle');
  });
});

describe('pageTitle', () => {
  it("is the first heading, without the writer's comment or Markdown marks", () => {
    expect(pageTitle('<!-- generated by mkp -->\n\n# The *coast* walk\n\n## Legs', 'doc')).toBe('The coast walk');
    expect(pageTitle('No heading here.', 'doc')).toBe('doc');
  });
});

describe('markdownToHtml without a sanitiser', () => {
  it('shows raw HTML as text, and keeps comments', () => {
    const html = markdownToHtml('<!-- generated by mkp -->\n\nHi <b onclick="x()">there</b>.\n\n<script>alert(1)</script>\n');
    expect(html).toContain('<!-- generated by mkp -->');
    expect(html).not.toContain('<script>');
    expect(html).not.toContain('<b onclick');
    expect(html).toContain('&lt;script&gt;');
  });
});

describe('pictures inside the page', () => {
  it('finds the pictures a document names, and swaps them for data: URLs', () => {
    const c = compile({ packs: [] });
    const b = c.document('# Plan\n\n![The flat](plan.svg)\n\nSee [the site](https://example.com/a.png).\n', 'doc.mkp.md')!;
    expect(c.diags.errors).toEqual([]);
    expect(pictureNames(b)).toEqual(['plan.svg']);
    const swapped = JSON.stringify(withAssets(b, { 'plan.svg': 'data:image/svg+xml;base64,AAAA' }));
    expect(swapped).toContain('data:image/svg+xml;base64,AAAA');
    expect(swapped).not.toContain('](plan.svg');
    expect(swapped).toContain('https://example.com/a.png');
  });
});
